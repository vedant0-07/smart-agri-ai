/* ─── Draw AI result on TFT ─────────────────────────────────── */
static void draw_result(const char *label, uint8_t conf_pct) {
    char conf_str[8];

    /* Format confidence string: "87%" */
    if (conf_pct >= 100)
        snprintf(conf_str, sizeof(conf_str), "100%%");
    else if (conf_pct >= 10)
        snprintf(conf_str, sizeof(conf_str), " %d%%", conf_pct);
    else
        snprintf(conf_str, sizeof(conf_str), "  %d%%", conf_pct);

    /* ── Clear result areas ───────────────────────────────── */
    tft_fill_rect(0, 55,  240, 36, C_BG);   /* label area   */
    tft_fill_rect(0, 113, 240, 36, C_BG);   /* conf area    */
    tft_fill_rect(0, 154, 240, 14, C_BBAR); /* bar area     */
    tft_fill_rect(0, 170, 240, 10, C_BG);   /* below bar    */

    /* ── Draw label (2× scale, white) ────────────────────── */
    tft_draw_str(4, 58, label, C_WHITE, C_BG, 2);

    /* ── Draw confidence value (2× scale, yellow) ────────── */
    tft_draw_str(4, 116, conf_str, C_YELO, C_BG, 2);

    /* ── Draw confidence bar ─────────────────────────────── */
    uint16_t bar_w = (uint16_t)((uint32_t)conf_pct * 230 / 100);
    /* Bar background (full width) */
    tft_fill_rect(4, 154, 230, 14, C_BBAR);
    /* Bar fill (proportional) */
    if (bar_w > 0)
        tft_fill_rect(4, 154, bar_w, 14, C_BFIL);

    /* LED indicator via GPIO2 */
    XGpio_DiscreteWrite(&gpio, 2,
        (conf_pct > 75) ? 0x0F :
        (conf_pct > 50) ? 0x07 :
        (conf_pct > 25) ? 0x03 : 0x01);
}

/* ─── UART result parser ─────────────────────────────────────
 * Protocol: 0xBB [len] [label bytes] [conf%] 0xCC
 * Returns 1 if a complete result was parsed
 */
#define PROTO_START 0xBB
#define PROTO_END   0xCC
#define MAX_LABEL   20

static char   last_label[MAX_LABEL + 1];
static uint8_t last_conf;

typedef enum {
    PS_IDLE = 0,
    PS_LEN,
    PS_LABEL,
    PS_CONF,
    PS_END
} ParseState;

static int parse_uart(void) {
    static ParseState  state    = PS_IDLE;
    static uint8_t     rx_label[MAX_LABEL];
    static uint8_t     label_len = 0;
    static uint8_t     char_cnt  = 0;
    static uint8_t     rx_conf   = 0;
    uint8_t byte;
    int got_result = 0;

    /* Drain all available bytes */
    while (XUartLite_Recv(&uart, &byte, 1) == 1) {
        switch (state) {
        case PS_IDLE:
            if (byte == PROTO_START) {
                memset(rx_label, ' ', MAX_LABEL);
                char_cnt  = 0;
                label_len = 0;
                state     = PS_LEN;
            }
            break;

        case PS_LEN:
            label_len = (byte > MAX_LABEL) ? MAX_LABEL : byte;
            state     = PS_LABEL;
            break;

        case PS_LABEL:
            if (char_cnt < label_len && char_cnt < MAX_LABEL)
                rx_label[char_cnt] = byte;
            char_cnt++;
            if (char_cnt >= label_len)
                state = PS_CONF;
            break;

        case PS_CONF:
            rx_conf = byte;
            state   = PS_END;
            break;

        case PS_END:
            if (byte == PROTO_END) {
                /* Copy result */
                memcpy(last_label, rx_label, MAX_LABEL);
                last_label[MAX_LABEL] = '\0';
                /* Trim trailing spaces */
                for (int i = MAX_LABEL - 1; i >= 0 && last_label[i] == ' '; i--)
                    last_label[i] = '\0';
                last_conf  = rx_conf;
                got_result = 1;
            }
            state = PS_IDLE;
            break;
        }
    }
    return got_result;
}

/* ─── Main ─────────────────────────────────────────────────── */
int main(void) {
    xil_printf("\r\n===================================\r\n");
    xil_printf("  Smart Agriculture AI TFT Display\r\n");
    xil_printf("  MicroBlaze on 3EDGE Artix-7\r\n");
    xil_printf("===================================\r\n");

    /* ── Init UART (ESP32) ─────────────────────────────────── */
    XUartLite_Initialize(&uart, UART_DEVICE_ID);
    XUartLite_ResetFifos(&uart);
    xil_printf("UART ready (115200 baud)\r\n");

    /* ── Init GPIO ─────────────────────────────────────────── */
    XGpio_Initialize(&gpio, GPIO_DEVICE_ID);
    XGpio_SetDataDirection(&gpio, 1, 0x00);  /* Channel 1 = outputs (TFT ctrl) */
    XGpio_SetDataDirection(&gpio, 2, 0x00);  /* Channel 2 = outputs (LEDs) */
    gpio_val = 0;
    RST_HI(); DC_DAT();

    /* ── Init SPI ─────────────────────────────────────────── */
    XSpi_Config *spi_cfg = XSpi_LookupConfig(SPI_DEVICE_ID);
    XSpi_CfgInitialize(&spi, spi_cfg, spi_cfg->BaseAddress);
    XSpi_SetOptions(&spi,
        XSP_MASTER_OPTION |
        XSP_CLK_ACTIVE_LOW_OPTION |  /* CPOL=0 */
        XSP_CLK_PHASE_1_OPTION |     /* CPHA=0 */
        XSP_MANUAL_SSELECT_OPTION);
    XSpi_SetSlaveSelect(&spi, 0x01);
    XSpi_Start(&spi);
    XSpi_IntrGlobalDisable(&spi);
    xil_printf("SPI ready\r\n");

    /* ── Init ILI9341 TFT ─────────────────────────────────── */
    xil_printf("Initializing TFT display...\r\n");
    tft_init();
    draw_static_ui();
    xil_printf("TFT ready!\r\n");

    /* LED: idle = 1 LED on */
    XGpio_DiscreteWrite(&gpio, 2, 0x01);

    xil_printf("Waiting for AI results from ESP32...\r\n");
    xil_printf("(ESP32 should POST to /result endpoint)\r\n\r\n");

    /* ── Main loop ─────────────────────────────────────────── */
    while (1) {
        if (parse_uart()) {
            xil_printf("Result: [%s] %d%%\r\n", last_label, last_conf);
            draw_result(last_label, last_conf);
        }

        /* Small delay to avoid CPU spin */
        usleep(1000);
    }

    return 0;
}
