/* ─── Peripheral instances ─────────────────────────────────── */
static XUartLite uart;
static XGpio     gpio;
static XSpi      spi;

/* ─── GPIO macros ──────────────────────────────────────────── */
static uint32_t gpio_val = 0;

static void gpio_set(uint32_t mask)  {
    gpio_val |=  mask;
    XGpio_DiscreteWrite(&gpio, 1, gpio_val);
}
static void gpio_clr(uint32_t mask)  {
    gpio_val &= ~mask;
    XGpio_DiscreteWrite(&gpio, 1, gpio_val);
}

#define DC_CMD()  gpio_clr(TFT_DC_BIT)
#define DC_DAT()  gpio_set(TFT_DC_BIT)
#define RST_LO()  gpio_clr(TFT_RST_BIT)
#define RST_HI()  gpio_set(TFT_RST_BIT)

/* ─── SPI send byte ────────────────────────────────────────── */
static void spi_send(uint8_t byte) {
    uint8_t buf[1] = { byte };
    XSpi_Transfer(&spi, buf, NULL, 1);
}

/* ─── ILI9341 command/data ─────────────────────────────────── */
static void tft_cmd(uint8_t cmd) {
    DC_CMD();
    spi_send(cmd);
}

static void tft_dat(uint8_t dat) {
    DC_DAT();
    spi_send(dat);
}

static void tft_dat16(uint16_t val) {
    DC_DAT();
    spi_send(val >> 8);
    spi_send(val & 0xFF);
}

/* ─── Set pixel window ─────────────────────────────────────── */
static void tft_set_window(uint16_t x1, uint16_t y1,
                            uint16_t x2, uint16_t y2) {
    tft_cmd(0x2A);
    tft_dat(x1 >> 8); tft_dat(x1 & 0xFF);
    tft_dat(x2 >> 8); tft_dat(x2 & 0xFF);

    tft_cmd(0x2B);
    tft_dat(y1 >> 8); tft_dat(y1 & 0xFF);
    tft_dat(y2 >> 8); tft_dat(y2 & 0xFF);

    tft_cmd(0x2C);
    DC_DAT();
}

/* ─── Fill rectangle with solid color ─────────────────────── */
static void tft_fill_rect(uint16_t x, uint16_t y,
                           uint16_t w, uint16_t h,
                           uint16_t color) {
    tft_set_window(x, y, x + w - 1, y + h - 1);
    uint32_t n = (uint32_t)w * h;
    while (n--) tft_dat16(color);
}

/* ─── Draw one character (scale 1× or 2×) ─────────────────── */
static void tft_draw_char(uint16_t x, uint16_t y,
                           char c,
                           uint16_t fg, uint16_t bg,
                           uint8_t scale) {
    if (c < 0x20 || c > 0x7E) c = 0x20;
    const uint8_t *bmap = font8x8[c - 0x20];
    uint16_t cw = 8 * scale;
    uint16_t ch = 8 * scale;

    tft_set_window(x, y, x + cw - 1, y + ch - 1);

    for (int row = 0; row < 8; row++) {
        for (int sr = 0; sr < scale; sr++) {
            for (int col = 0; col < 8; col++) {
                uint16_t color = (bmap[row] & (0x80 >> col)) ? fg : bg;
                for (int sc = 0; sc < scale; sc++) {
                    tft_dat16(color);
                }
            }
        }
    }
}

/* ─── Draw string (scale 1× or 2×) ─────────────────────────── */
static void tft_draw_str(uint16_t x, uint16_t y,
                          const char *s,
                          uint16_t fg, uint16_t bg,
                          uint8_t scale) {
    while (*s) {
        tft_draw_char(x, y, *s++, fg, bg, scale);
        x += 8 * scale;
        if (x + 8 * scale > 240) break;
    }
}

/* ─── ILI9341 initialization sequence ─────────────────────── */
static void tft_init(void) {
    /* Hardware reset */
    RST_LO(); usleep(20000);
    RST_HI(); usleep(150000);

    tft_cmd(0x01); usleep(150000); /* SWRESET */
    tft_cmd(0x11); usleep(255000); /* SLPOUT  */

    tft_cmd(0x3A); tft_dat(0x55); /* COLMOD: 16-bit color */
    tft_cmd(0x36); tft_dat(0x48); /* MADCTL: portrait, BGR */

    /* Display area */
    tft_cmd(0x2A);
    tft_dat(0x00); tft_dat(0x00);
    tft_dat(0x00); tft_dat(0xEF); /* 240 */

    tft_cmd(0x2B);
    tft_dat(0x00); tft_dat(0x00);
    tft_dat(0x01); tft_dat(0x3F); /* 320 */

    tft_cmd(0x13);                /* NORON  */
    tft_cmd(0x20);                /* INVOFF */
    tft_cmd(0x29); usleep(25000); /* DISPON */

    /* Clear to background */
    tft_fill_rect(0, 0, 240, 320, C_BG);
}

